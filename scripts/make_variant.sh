#!/bin/bash
# Create a wrapper policy/prefetcher file that overrides some knobs of an
# existing one, without copying its code.
#
#   scripts/make_variant.sh replacement/dyn_irrip.l2c_repl dyn_irrip_t010 DIRRIP_THRESHOLD=0.10
#   scripts/make_variant.sh prefetcher/spp.l1d_pref spp_acc80 SPP_ACC_HIGH=0.80 SPP_DEGREE_HIGH=6
#
# writes replacement/dyn_irrip_t010.l2c_repl (same directory and extension as the source),
# which can then be built with ./build_champsim.sh ... dyn_irrip_t010 ...
# All knobs in the PA2 files are #ifndef-guarded, which is what makes this work.
set -euo pipefail
if [ "$#" -lt 3 ]; then
  echo "usage: $0 <source file> <variant name> KEY=VALUE [KEY=VALUE ...]" >&2
  exit 1
fi
src=$1; name=$2; shift 2
dir=$(dirname "$src"); base=$(basename "$src"); ext=${base##*.}
out="$dir/$name.$ext"
{
  echo "// Auto-generated by scripts/make_variant.sh from $base. Do not edit; re-generate instead."
  for kv in "$@"; do
    echo "#define ${kv%%=*} ${kv#*=}"
  done
  echo "#include \"$base\""
} > "$out"
echo "$out"
